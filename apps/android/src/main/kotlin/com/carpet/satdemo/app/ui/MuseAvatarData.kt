    internal fun greyIndex(c: Int): Int {
        val r = (c shr 16) and 0xFF
        val g = (c shr 8) and 0xFF
        val b = c and 0xFF
        val l = (r * 3 + g * 6 + b) / 10
        val q = when {
            l > 200 -> 0
            l > 150 -> 1
            l > 100 -> 2
            else -> 3
        }
        return GREY_BASE + q
    }

