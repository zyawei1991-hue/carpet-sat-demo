#!/usr/bin/env python3
"""Bake Xiaomo's five 64x64 states into the firmware palette."""

from collections import Counter
from pathlib import Path

from PIL import Image, ImageDraw

SCREEN = Path(__file__).resolve().parents[1]
AVATAR = SCREEN / "muse" / "avatar"
SOURCE = AVATAR / "source"
PREVIEW = AVATAR / "preview"
HEADER = AVATAR / "muse_pixel_sprites.h"

PALETTE = [
    ("C_BG", 0x000000),
    ("C_OUT", 0x3A2B22),
    ("C_OUT2", 0x8C8268),
    ("C_BD", 0xB3A98F),
    ("C_BM", 0xD3C9AE),
    ("C_BL", 0xEAE2CA),
    ("C_BH", 0xFBF5E6),
    ("C_SKIND", 0x10151E),
    ("C_SKIN", 0x1B2330),
    ("C_SKINL", 0x262F40),
    ("C_IRIS", 0xEFE6D0),
    ("C_SHINE", 0xFFFFFF),
    ("C_BROW", 0xC9C0AB),
    ("C_BLUSH", 0xF4AAA0),
    ("C_BLUSHD", 0xEA8F8E),
    ("C_MOUTH", 0xD8C9AC),
    ("C_TONGUE", 0xE86A7A),
    ("C_BELL", 0xFFC94A),
    ("C_BELLD", 0xC98A2A),
    ("C_EDGE", 0x8A93A6),
]

STATES = ("idle", "listening", "speaking", "happy", "error")


def rgb(value):
    return ((value >> 16) & 255, (value >> 8) & 255, value & 255)


def remove_bell(im):
    im = im.copy()
    for y in range(37, 50):
        left = im.getpixel((28, y))
        right = im.getpixel((36, y))
        for x in range(29, 36):
            t = (x - 28) / 8
            im.putpixel((x, y), tuple(round(a + (b - a) * t) for a, b in zip(left, right)))
    return im


def make_happy(idle, speaking):
    im = idle.copy()
    im.paste(speaking.crop((20, 20, 44, 35)), (20, 20))
    return im


def make_error(idle):
    im = idle.copy()
    draw = ImageDraw.Draw(im)
    brow = rgb(0xC9C0AB)
    mouth = rgb(0xD8C9AC)
    blush = rgb(0xEA8F8E)
    for y in range(28, 34):
        for x in range(29, 36):
            im.putpixel((x, y), idle.getpixel((x, 26)))
    draw.line((23, 21, 26, 20), fill=brow, width=1)
    draw.line((38, 20, 41, 21), fill=brow, width=1)
    draw.point((30, 31), fill=mouth)
    draw.point((31, 32), fill=mouth)
    draw.point((32, 31), fill=mouth)
    draw.point((33, 32), fill=mouth)
    draw.point((34, 31), fill=mouth)
    draw.point((22, 28), fill=blush)
    draw.point((23, 27), fill=blush)
    draw.point((41, 27), fill=blush)
    draw.point((42, 28), fill=blush)
    return im


def nearest(color):
    return min(
        range(len(PALETTE)),
        key=lambda i: sum((a - b) ** 2 for a, b in zip(color, rgb(PALETTE[i][1]))),
    )


def indexed(im):
    return [nearest(im.getpixel((x, y))) for y in range(64) for x in range(64)]


def main():
    PREVIEW.mkdir(parents=True, exist_ok=True)
    images = {}
    for name in ("idle", "listening", "speaking"):
        images[name] = remove_bell(
            Image.open(SOURCE / f"xiaomo_{name}.png").convert("RGB").resize(
                (64, 64), Image.Resampling.LANCZOS
            )
        )
    images["happy"] = make_happy(images["idle"], images["speaking"])
    images["error"] = make_error(images["idle"])

    arrays = {name: indexed(im) for name, im in images.items()}
    lines = [
        "#pragma once",
        "",
        "/* Generated by firmware/screen/tools/bake_xiaomo.py. */",
        "static const uint8_t XIAOMO_PALETTE[] = {",
        "    " + ", ".join(name for name, _ in PALETTE),
        "};",
        "",
    ]
    for name in STATES:
        lines.append(f"static const uint8_t XIAOMO_{name.upper()}[MUSE_PX_W * MUSE_PX_H] = {{")
        data = arrays[name]
        for start in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(i) for i in data[start:start + 24]) + ",")
        lines.extend(["};", ""])
    HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    sheet = Image.new("RGB", (64 * len(STATES) * 4, 64 * 4), 0x000000)
    for i, name in enumerate(STATES):
        im = Image.new("RGB", (64, 64), 0x000000)
        im.putdata([rgb(PALETTE[index][1]) for index in arrays[name]])
        im.resize((512, 512), Image.Resampling.NEAREST).save(PREVIEW / f"xiaomo_{name}_64.png")
        sheet.paste(im.resize((256, 256), Image.Resampling.NEAREST), (i * 256, 0))
    sheet.save(PREVIEW / "xiaomo_five_states.png")

    for name in STATES:
        counts = Counter(PALETTE[i][0] for i in arrays[name])
        print(f"{name}: {len(arrays[name])} pixels, {len(counts)} colors")
    print(f"header: {HEADER} ({HEADER.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
